List<Map<String, dynamic>> getFavoriteMovies() {
  final List<Map<String, dynamic>> combined = [
    ...nowPlayingMovies,
    ...trendingMovies,
    ...popularMovies,
    ...topRatedMovies,
  ];

  for (final list in genreMovies.values) {
    combined.addAll(list);
  }

  final Map<String, Map<String, dynamic>> uniqueMap = {};
  for (final movie in combined) {
    final title = movie['title'] as String? ?? '';
    if (title.isNotEmpty && movie['is_favourited'] == true) {
      uniqueMap[title] = movie;
    }
  }

  return uniqueMap.values.toList();
}
